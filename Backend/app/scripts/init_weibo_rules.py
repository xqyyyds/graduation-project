def init_weibo_rules():
    logger.info(
        f" 正在全量初始化《微博投诉操作细则》，共准备了 {len(WEIBO_RULES_DATA)} 条核心规则..."
    )

    docs = []

    for rule in WEIBO_RULES_DATA:
        # 1. 构造 page_content (Embedding Target)
        # 策略：只放最核心的语义信息，方便 Agent C 检索
        # 格式：“[大类] 具体行为”
        content = f"[{rule['category']}] {rule['behavior']}"

        # 2. 构造 metadata (Payload)
        # 策略：放入所有详情，Agent C 检索到后，会读取这些字段来生成报告
        meta = {
            "source": "微博投诉操作细则",
            "category": rule.get("category"),  # 违规大类
            "article": rule.get("article"),  # 条款号 (如：第六条)
            "risk_level": rule.get("risk"),  # 风险等级 (High/Medium/Low)
            "full_desc": rule.get("behavior"),  # 完整描述
        }

        doc = Document(page_content=content, metadata=meta)
        docs.append(doc)

    # 3. 写入 ChromaDB
    if docs:
        logger.info(f" 正在将数据写入向量数据库...")
        chroma_db.add_documents(docs)
        logger.info(" 全量入库完成！你的 Agent C 现在熟读了整本微博管理细则。")


if __name__ == "__main__":
    # 为了保证数据不重复，建议先清空一次
    logger.warning(" 正在清空旧数据...")
    chroma_db.clear_db()

    init_weibo_rules()
